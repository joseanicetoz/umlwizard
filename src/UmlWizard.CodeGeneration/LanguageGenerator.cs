using UmlWizard.Core.Model;

namespace UmlWizard.CodeGeneration;

/// <summary>Writes the types of a <see cref="CodeModel"/> in one language.</summary>
public abstract class LanguageGenerator(CodeModel model, CodeGenerationOptions options, IList<string> warnings)
{
    protected CodeModel Model { get; } = model;

    protected CodeGenerationOptions Options { get; } = options;

    protected IList<string> Warnings { get; } = warnings;

    /// <summary>The comment text at the top of every file.</summary>
    protected string GeneratedBy => $"Generated by UML Wizard from the class diagram \"{Options.DiagramName}\".";

    /// <summary>The files of one type, e.g. a header and a source file in C++.</summary>
    public abstract IEnumerable<GeneratedFile> Generate(TypeModel type);

    /// <summary>A default value as written in the diagram, with <c>null</c> spelled the language's way.</summary>
    protected static string DefaultValue(string value, string nullLiteral) =>
        value.Trim() is "null" or "nil" or "None" or "nullptr" ? nullLiteral : value.Trim();

    /// <summary>
    /// The default value of an attribute, with a literal of an enumeration of the diagram ("New", or "OrderStatus.New")
    /// written by <paramref name="literal"/> the way the language refers to it, e.g. <c>OrderStatus::New</c>.
    /// </summary>
    protected string AttributeDefault(UmlAttribute attribute, string nullLiteral, Func<TypeModel, UmlAttribute, string> literal)
    {
        var value = attribute.DefaultValue!.Trim();
        if (attribute.Type is { } type && Model.Find(type.Trim()) is { IsEnum: true } enumeration)
        {
            var name = value[(value.LastIndexOfAny(['.', ':']) + 1)..];
            if (enumeration.Class.Attributes.FirstOrDefault(a => a.Name == name || Naming.Identifier(a.Name) == name) is { } match)
            {
                return literal(enumeration, match);
            }
        }

        return DefaultValue(value, nullLiteral);
    }

    /// <summary>The name with <paramref name="suffix"/> appended when it is a keyword of the language.</summary>
    protected static string AvoidKeyword(string name, ISet<string> keywords, string suffix = "_") =>
        keywords.Contains(name) ? name + suffix : name;

    /// <summary>The language-neutral key of a built-in type name (see <see cref="BuiltInTypes.Key"/>).</summary>
    protected static string? BuiltIn(string name) => BuiltInTypes.Key(name);

    /// <summary>The operations of a type, constructors first.</summary>
    protected static IEnumerable<OperationModel> ConstructorsFirst(TypeModel type) =>
        type.Operations.Where(o => o.IsConstructor).Concat(type.Operations.Where(o => !o.IsConstructor));
}
