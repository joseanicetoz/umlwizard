using System.Globalization;
using System.Text.RegularExpressions;
using Avalonia.Controls;
using Avalonia.Headless.XUnit;
using UmlWizard.App.Resources;
using UmlWizard.Core.Model;

namespace UmlWizard.App.Tests;

public sealed partial class LocalizationTests
{
    private static string AppFolder([System.Runtime.CompilerServices.CallerFilePath] string testFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(testFile)!, "..", "..", "src", "UmlWizard.App"));

    /// <summary>Attributes whose fixed text the user reads; <c>{x:Static res:Strings.…}</c> values come from the resources.</summary>
    [GeneratedRegex("""\b(Header|Text|Title|ToolTip\.Tip|Content|Watermark)="(?<text>[^"{][^"]*)"|ConverterParameter='(?<text>[^']*)'""")]
    private static partial Regex LiteralText();

    /// <summary>Fixed texts that are not words: a separator glyph and <c>SizeToContent</c> values.</summary>
    private static readonly string[] NotText = [" → ", "Height", "WidthAndHeight"];

    [Fact]
    public void TheViews_TakeTheirTextFromTheResources()
    {
        var files = Directory.GetFiles(Path.Combine(AppFolder(), "Views"), "*.axaml", SearchOption.AllDirectories);
        Assert.NotEmpty(files);

        var literals = files
            .SelectMany(file => LiteralText().Matches(File.ReadAllText(file)).Select(m => (File: Path.GetFileName(file), m.Groups["text"].Value)))
            .Where(l => !NotText.Contains(l.Value))
            .ToList();

        Assert.True(literals.Count == 0, "Text not in Strings.resx: " + string.Join(", ", literals));
    }

    public static TheoryData<Type> DisplayedEnums =>
    [
        typeof(UmlVisibility), typeof(ClassifierKind), typeof(RelationshipKind), typeof(LifelineKind), typeof(MessageKind),
        typeof(HorizontalTextAlignment), typeof(VerticalTextAlignment), typeof(GraphNodeKind), typeof(GraphEdgeKind),
    ];

    [Theory]
    [MemberData(nameof(DisplayedEnums))]
    public void EveryDisplayedEnumValue_HasADisplayName(Type type)
    {
        foreach (Enum value in Enum.GetValues(type))
        {
            Assert.NotNull(Strings.ResourceManager.GetString($"Enum_{type.Name}_{value}", CultureInfo.InvariantCulture));
        }
    }

    [Fact]
    public void EveryDiagramType_HasADisplayNameAndANamePrefix()
    {
        foreach (var type in Enum.GetValues<DiagramType>())
        {
            Assert.NotNull(Strings.ResourceManager.GetString($"DiagramType_{type}", CultureInfo.InvariantCulture));
            Assert.NotNull(Strings.ResourceManager.GetString($"DiagramName_{type}", CultureInfo.InvariantCulture));
        }
    }

    /// <summary>A .resx value is taken literally: "\n" typed into it would be shown as a backslash and an n.</summary>
    [Fact]
    public void ResourceTexts_HaveRealLineBreaks_NotEscapes()
    {
        var texts = Strings.ResourceManager.GetResourceSet(CultureInfo.InvariantCulture, createIfNotExists: true, tryParents: true)!;
        foreach (System.Collections.DictionaryEntry entry in texts)
        {
            Assert.DoesNotContain("\\n", (string)entry.Value!);
        }

        Assert.Contains("already exists in\n", Strings.Message_ReplaceFile);
    }

    /// <summary>
    /// Strings.Designer.cs is checked in and regenerated by Rider and Visual Studio when Strings.resx is saved; a string
    /// added or removed in another editor leaves it behind.
    /// </summary>
    [Fact]
    public void TheStringsClass_MatchesStringsResx()
    {
        var keys = System.Xml.Linq.XDocument.Load(Path.Combine(AppFolder(), "Resources", "Strings.resx"))
            .Root!.Elements("data").Select(d => (string)d.Attribute("name")!).ToHashSet();
        var properties = typeof(Strings).GetProperties(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)
            .Where(p => p.PropertyType == typeof(string)).Select(p => p.Name).ToHashSet();

        var missing = keys.Except(properties).Order().ToList();
        var stale = properties.Except(keys).Order().ToList();
        Assert.True(missing.Count == 0 && stale.Count == 0,
            "Strings.Designer.cs is out of date; open Strings.resx in Rider or Visual Studio and save it to regenerate it. "
            + $"Missing: {string.Join(", ", missing)}. No longer in Strings.resx: {string.Join(", ", stale)}.");
    }

    [Fact]
    public void EnumValues_WithoutADisplayName_FallBackToTheirName()
    {
        Assert.Equal("Association", Loc.Of(RelationshipKind.Association));
        Assert.Equal(nameof(DayOfWeek.Monday), Loc.Of(DayOfWeek.Monday));
    }

    [AvaloniaFact]
    public void EnumValues_AreShownByTheirDisplayNames_EverywhereInTheApp()
    {
        var template = Assert.Single(Avalonia.Application.Current!.DataTemplates.OfType<EnumDataTemplate>());

        Assert.True(template.Match(RelationshipKind.DirectedAssociation));
        Assert.False(template.Match("text"));
        var text = Assert.IsType<TextBlock>(template.Build(GraphEdgeKind.CommunicationPath));
        Assert.Equal(Strings.Enum_GraphEdgeKind_CommunicationPath, text.Text);
    }
}
